#!/usr/bin/env node
// Test/dev fixture of the start camp «Перепутье»: the layout campmap.js computes (LGCampMap.get()) and its walk grid
// (LGCampMap.map(): citymap.js makeFrom) as plain data → test/fixtures/camp-map.json. Same idea as fair-map.json: data
// snapshot for tests and dev pages only (never bundled into the extension, which reads the live window.LGCampMap).
//   node scripts/fixture-camp.mjs .local/site-1027
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dir = process.argv[2];
if (!dir) { console.error('usage: node scripts/fixture-camp.mjs <dir with citymap.js and campmap.js>'); process.exit(1); }
const load = (f, req) => {
  const module = { exports: {} };
  vm.runInNewContext(readFileSync(join(dir, f), 'utf8'), { module, exports: module.exports, require: req || (() => ({})), console, Math, JSON, Date }, { timeout: 5000 });
  return module.exports;
};
const CM = load('citymap.js');
const CAMP = load('campmap.js', () => CM);
const L = CAMP.get(), m = CAMP.map(L);
const err = CAMP.check(L);
if (err.length) { console.error('campmap.js check():', err); process.exit(1); }
const { C, cols, rows, G } = m.grid;
const out = {
  about: 'Start camp «Перепутье» layout + walk grid, generated by scripts/fixture-camp.mjs from the site scripts (campmap.js + citymap.js). Tests and dev pages only.',
  id: L.id, name: L.name, W: L.W, H: L.H, AREA: L.AREA, FENCE: L.FENCE, BUILDINGS: L.BUILDINGS, OBST: L.OBST,
  fire: L.fire, tents: L.tents, props: L.props, lines: L.lines, trail: L.trail, spawn: L.spawn,
  grid: { C, cols, rows, G: Array.from(G, (v) => (v ? 1 : 0)).join('') },
};
writeFileSync(join(ROOT, 'test/fixtures/camp-map.json'), JSON.stringify(out) + '\n');
console.log(`camp fixture: ${L.BUILDINGS.length} buildings, ${L.tents.length} tents, ${L.props.length} props, grid ${cols}×${rows} (C=${C}) → test/fixtures/camp-map.json`);
