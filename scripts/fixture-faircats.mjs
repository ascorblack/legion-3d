#!/usr/bin/env node
// Test/dev fixture of the new cats fair («новая Ярмарка», site 04.11, hero flag me.fc): the geometry fc-map.js exports
// (window.LGFairCats — a UMD module, pure numbers: town polygon, rims, stairs, streets, buildings with vis/foot/door,
// houses, decor items, wall, jail) and its walk grid (make(): 16 px cells, levels 0 = blocked, 1 = town, 2 = plateau,
// 3 = stairs; the jail variant as [cell, count, value] runs) → test/fixtures/faircats-map.json. Same idea as
// camp-map.json: numbers only, for tests and dev pages (never bundled; the extension reads the live window.LGFairCats).
//   node scripts/fixture-faircats.mjs .local/site-1104-0007
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dir = process.argv[2];
if (!dir) { console.error('usage: node scripts/fixture-faircats.mjs <dir with fc-map.js>'); process.exit(1); }
const G0 = { console, Math, JSON, Date, Map, Set, Uint8Array, Uint32Array, Int32Array, Float32Array, Object, Array, Number, String, Infinity, NaN };
const load = (file, req) => { const module = { exports: {} }; vm.runInNewContext(readFileSync(join(dir, file), 'utf8'), { ...G0, module, exports: module.exports, require: req }, { timeout: 10000 }); return module.exports; };
// since 05.11 fc-map.js is built on the Town Kit (node: require('../townkit/tkmap.js') = tk-map.js, window.LGTownKitMap)
let K = null;
try { K = load('tk-map.js'); } catch { /* an older site copy: fc-map.js stands alone */ }
const F = load('fc-map.js', (p) => { if (K && /tkmap|tk-map/.test(p)) return K; throw new Error('require ' + p); });
if (!F || typeof F.make !== 'function') { console.error('fc-map.js did not export LGFairCats'); process.exit(1); }
const m0 = F.make({}), m1 = F.make({ jail: true });
const patch = [];
for (let i = 0; i < m0.G.length;) {
  if (m0.G[i] === m1.G[i]) { i++; continue; }
  let n = 0; const v = m1.G[i];
  while (i + n < m0.G.length && m1.G[i + n] === v && m0.G[i + n] !== v) n++;
  patch.push([i, n, v]); i += n;
}
const plain = (o) => JSON.parse(JSON.stringify(o));
const out = {
  about: 'New cats fair (site fc-map.js, window.LGFairCats, hero flag me.fc): geometry + walk grid levels (0 blocked, 1 town, 2 plateau, 3 stairs), generated by scripts/fixture-faircats.mjs. Tests and dev pages only.',
  W: F.W, H: F.H, FACE: F.FACE, MFACE: F.MFACE, PAD: F.PAD, SPEED: F.SPEED, SCALE: F.SCALE, RAIL: F.RAIL,
  RIM: F.RIM, MRIM: F.MRIM, TOWN: F.TOWN, PLATEAU: F.PLATEAU, SIDE_W: F.SIDE_W, MOUNT: F.MOUNT,
  STAIRS: F.STAIRS, STREETS: F.STREETS, PATHS: F.PATHS, RAILS: F.RAILS, POND: F.POND, PIER: F.PIER,
  BUILDINGS: F.BUILDINGS, HOUSES: F.HOUSES, ITEMS: F.ITEMS, WALL: F.WALL, JAIL: F.JAIL,
  OBST: plain(m0.OB.map(({ box, ...o }) => o)),
  grid: { C: m0.C, cols: m0.cols, rows: m0.rows, G: Array.from(m0.G).join(''), jailPatch: patch },
  home: m0.home, spawn: m0.spawn,
};
writeFileSync(join(ROOT, 'test/fixtures/faircats-map.json'), JSON.stringify(plain(out)) + '\n');
const lv = [0, 0, 0, 0]; for (const v of m0.G) lv[v]++;
console.log(`faircats fixture: ${F.BUILDINGS.length} buildings, ${F.HOUSES.length} houses, ${F.ITEMS.length} items, grid ${m0.cols}×${m0.rows} levels ${lv.join('/')}, jail patch ${patch.length} runs → test/fixtures/faircats-map.json`);
